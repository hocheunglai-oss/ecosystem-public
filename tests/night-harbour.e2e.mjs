import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
const BASE = process.env.ECO_DEMO_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const context = await browser.newContext({ viewport: { width: 1671, height: 941 } });
  await context.addInitScript(() => {
    const upload = WebGLRenderingContext.prototype.texImage2D;
    WebGLRenderingContext.prototype.texImage2D = function (...args) {
      const image = args[args.length - 1];
      if (image instanceof HTMLImageElement) window.__waterPlate = image.currentSrc;
      return upload.apply(this, args);
    };
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(BASE);
  await page.getByLabel('Demo profile', { exact: true }).selectOption('gianmichele');
  await page.getByRole('button', { name: 'ENTER ECOSYSTEM', exact: true }).click();
  await page.waitForTimeout(800);
  const records = () => page.evaluate(() => Object.fromEntries(Object.entries(localStorage).filter(([key]) => key !== 'ecosystem.theme.v1')));
  const before = await records();
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.marine-world__water')?.dataset.waterState === 'running' && window.__waterPlate?.endsWith('destination-oil-terminal-night-v2.jpg'));
  assert.equal(await page.locator('.marine-birds').count(), 0);
  assert.equal(await page.locator('[data-lighthouse]').count(), 3);
  assert.equal(await page.locator('[data-cosulich-barge]').count(), 2);
  const bargeLighting = () => page.locator('[data-cosulich-barge] image').evaluateAll(images => images.map(image => {
    const id = image.getAttribute('filter')?.match(/^url\(#(.+)\)$/)?.[1];
    return id ? document.getElementById(id)?.querySelector('feFuncR')?.getAttribute('slope') : null;
  }));
  assert.ok((await bargeLighting()).every(slope => slope === '.624'), 'Both stationary barges must match night lighting');
  assert.equal(await page.locator('.fleet-berth, .destination-tanker, .voyage-status').count(), 0);
  const bargePosition = () => page.locator('[data-cosulich-barge] image').evaluateAll(images => images.map(node => ({ vessel: node.closest('[data-cosulich-barge]').dataset.cosulichBarge, transform: getComputedStyle(node).transform, box: node.getBoundingClientRect().toJSON() })));
  const moored = await bargePosition();
  assert.equal(await page.locator('.marine-world__harbour').evaluate(img => img.currentSrc), await page.evaluate(() => window.__waterPlate));
  const transforms = () => page.locator('.marine-lighthouse__beam').evaluateAll(beams => beams.map(beam => getComputedStyle(beam).transform));
  const first = await transforms();
  await page.waitForTimeout(450);
  (await transforms()).forEach((value, index) => assert.notEqual(value, first[index], 'Every lighthouse beam should rotate'));
  assert.deepEqual(await bargePosition(), moored, 'Both barges must stay stationary while ambient scenery moves');
  await page.reload();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  assert.deepEqual(await records(), before, 'Changing theme must preserve all demo records and session');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => document.querySelector('.marine-world')?.dataset.ambientMotion === 'paused');
  await page.waitForTimeout(150);
  const paused = await transforms();
  await page.waitForTimeout(300);
  assert.deepEqual(await transforms(), paused, 'Reduced motion must pause all lighthouse beams');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForFunction(() => document.querySelector('.marine-world')?.dataset.ambientMotion === 'running' && [...document.querySelectorAll('.marine-lighthouse__beam')].every(beam => getComputedStyle(beam).transform !== 'none'));
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.waitForTimeout(100);
  const hidden = await transforms();
  await page.waitForTimeout(300);
  assert.deepEqual(await transforms(), hidden, 'Hidden pages must pause all lighthouse beams');
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
  await page.getByRole('button', { name: 'Light mode', exact: true }).click();
  await page.waitForFunction(() => window.__waterPlate?.endsWith('destination-oil-terminal-clean-v7.jpg'));
  assert.equal(await page.locator('.marine-world__harbour').getAttribute('src'), '/marine/destination-oil-terminal-clean-v7.jpg');
  assert.equal(await page.locator('[data-company-flag="sculpture"]').count(), 1);
  assert.equal(await page.locator('.marine-birds').count(), 1);
  assert.equal(await page.locator('[data-lighthouse]').count(), 0);
  assert.equal(await page.locator('[data-cosulich-barge]').count(), 2);
  assert.ok((await bargeLighting()).every(slope => slope === '.96'), 'Neither daylight barge must retain night dimming');
  assert.deepEqual(errors, []);
  await context.close();
  console.log('PASS preserved records and Light artwork; lighthouse animations pause for reduced motion and hidden pages; matching night water and stationary barge treatment');
} finally { await browser.close(); }
